#!/usr/bin/env node
// Generated SDK API reference (DEVX-S4). Extracts the exported public surface + doc summaries
// from the SDK sources (siblings under citrate-labs/) and the CLI help, and emits ONE Atlas
// content page at content/sdks/_generated/api-reference.md. It lives under _generated/, which
// both build-content.mjs and content-lint.mjs skip, so it is machine-owned and lint-exempt;
// build-content.mjs explicitly re-includes it in the nav. Re-run on prebuild to stay in sync.
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LABS = path.resolve(ROOT, "..");
const JS = path.join(LABS, "citrate-sdk-js");
const PY = path.join(LABS, "citrate-sdk-python");
const OUT = path.join(ROOT, "content", "sdks", "_generated", "api-reference.md");

function read(p) {
  try { return fs.readFileSync(p, "utf8"); } catch { return null; }
}
function sha(repo) {
  try { return execSync("git rev-parse --short HEAD", { cwd: repo }).toString().trim(); } catch { return "unknown"; }
}
function firstLine(doc) {
  const line = (doc || "").split("\n").map((l) => l.replace(/^\s*\*\s?/, "").trim())
    .find((l) => l.length > 0) || "";
  return line.replace(/\.$/, "");
}

// ── JS: /** doc */ export <kind> Name ──────────────────────────────────────────
function jsSymbols(file) {
  const src = read(file);
  if (!src) return [];
  const out = [];
  // The doc-comment body must not contain */ (single comment, no backtracking across comments),
  // and must be immediately followed by the export it documents.
  const re = /\/\*\*((?:(?!\*\/)[\s\S])*?)\*\/\s*export\s+(?:async\s+)?(function|class|interface|type|const|enum)\s+(\w+)/g;
  let m;
  while ((m = re.exec(src)) !== null) out.push({ kind: m[2], name: m[3], summary: firstLine(m[1]) });
  return out;
}

// ── Python: top-level def/class + first docstring line ─────────────────────────
function pySymbols(file) {
  const src = read(file);
  if (!src) return [];
  const out = [];
  const re = /^(def|class)\s+(\w+)[^\n]*:[ \t]*\n(?:[ \t]+(?:r|f|)"""[ \t]*([^\n"]*))?/gm;
  let m;
  while ((m = re.exec(src)) !== null) {
    if (m[2].startsWith("_")) continue; // private
    out.push({ kind: m[1], name: m[2], summary: (m[3] || "").trim().replace(/\.$/, "") });
  }
  return out;
}

function section(title, symbols) {
  if (!symbols.length) return "";
  const rows = symbols.map((s) => `| \`${s.name}\` | ${s.kind} | ${s.summary || ""} |`).join("\n");
  return `\n### ${title}\n\n| Symbol | Kind | Summary |\n|---|---|---|\n${rows}\n`;
}

function cliHelp() {
  try {
    const help = execSync("python3 -m citrate_sdk.cli --help", { cwd: PY }).toString().trim();
    return "\n### citrate (Python)\n\n```text\n" + help + "\n```\n";
  } catch {
    return "\n### citrate (Python)\n\nRun `citrate --help` after `pip install citrate-ai-sdk`.\n";
  }
}

// Guard: if the sibling SDK repos are absent (e.g. an isolated Vercel/CI checkout of
// citrate-docs only), do NOT overwrite the committed api-reference.md with an empty one.
// The page is generated locally / in a siblings-present CI and committed; build-content
// consumes the committed copy.
if (!fs.existsSync(path.join(JS, "src", "index.ts")) || !fs.existsSync(path.join(PY, "citrate_sdk"))) {
  console.log("[gen-api-refs] sibling SDK repos not present; keeping the committed api-reference.md.");
  process.exit(0);
}

const jsSha = sha(JS), pySha = sha(PY);

let body = `---
title: SDK API reference (generated)
codex_slug: /sdks/api-reference
tier: public
org_scope: ~
source_kind: transcluded
source: scripts/gen-api-refs.mjs
status: Implemented
created: 2026-07-26T00:00:00Z
author: generated
---

This page is generated by \`scripts/gen-api-refs.mjs\` from the SDK sources on each build, so it
stays in sync with the code. It is the exported public surface; the narrative reference with
examples lives in [identity](/sdks/identity), [entitlements](/sdks/entitlements), and the
[JavaScript](/sdks/js) and [Python](/sdks/python) pages.

Sources: \`citrate-sdk-js@${jsSha}\`, \`citrate-sdk-python@${pySha}\`.

## JavaScript, @citratenetwork/sdk
`;

body += section("identity", [
  ...jsSymbols(path.join(JS, "src/identity/wallet.ts")),
  ...jsSymbols(path.join(JS, "src/identity/pkce.ts")),
  ...jsSymbols(path.join(JS, "src/identity/jwt.ts")),
  ...jsSymbols(path.join(JS, "src/identity/client.ts")),
]);
body += section("entitlements", jsSymbols(path.join(JS, "src/entitlements/capabilities.ts")));
body += section("gateway", jsSymbols(path.join(JS, "src/gateway/client.ts")));

body += `\n## Python, citrate-ai-sdk\n`;
body += section("citrate_sdk.identity", [
  ...pySymbols(path.join(PY, "citrate_sdk/identity/wallet.py")),
  ...pySymbols(path.join(PY, "citrate_sdk/identity/pkce.py")),
  ...pySymbols(path.join(PY, "citrate_sdk/identity/jwt.py")),
  ...pySymbols(path.join(PY, "citrate_sdk/identity/client.py")),
]);
body += section("citrate_sdk.entitlements", pySymbols(path.join(PY, "citrate_sdk/entitlements.py")));
body += section("citrate_sdk.gateway", pySymbols(path.join(PY, "citrate_sdk/gateway.py")));

body += `\n## Command line\n` + cliHelp();

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, body);
const jsCount = (body.match(/\| `/g) || []).length;
console.log(`[gen-api-refs] wrote ${path.relative(ROOT, OUT)} (${jsCount} symbols; js@${jsSha} py@${pySha})`);
