#!/usr/bin/env node
// Generate per-page freshness data: compare each page's `audited_against_sha`
// frontmatter to the current HEAD of its source repo (a sibling checkout) and
// record how many commits the source has moved since the page was audited.
//
// Committed output (content/_generated/freshness.ts): on Vercel the sibling
// repos are absent, so the committed snapshot is used. Regenerate where the
// siblings exist:  npm run docs:freshness
import fs from "node:fs";
import path from "node:path";
import { execSync } from "node:child_process";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const LABS = path.resolve(ROOT, "..");
const CONTENT = path.join(ROOT, "content");
const OUT = path.join(ROOT, "content", "_generated", "freshness.ts");

function walk(dir) {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...walk(p));
    else if (e.name.endsWith(".md")) out.push(p);
  }
  return out;
}

function frontmatter(raw) {
  const m = raw.match(/^﻿?---\n([\s\S]*?)\n---/);
  if (!m) return {};
  const fm = {};
  for (const line of m[1].split("\n")) {
    const i = line.indexOf(":");
    if (i < 0) continue;
    fm[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  return fm;
}

// The primary source repo is the leading path/word of the `source` field, when
// it names a sibling git checkout (e.g. "citrate-native/README.md, ..." or
// "citrate-chain cli/src/...").
function sourceRepo(source) {
  if (!source) return null;
  const first = source.split(",")[0].trim().split(/[/\s]/)[0];
  if (!first) return null;
  const dir = path.join(LABS, first);
  return fs.existsSync(path.join(dir, ".git")) ? { repo: first, dir } : null;
}

function git(dir, args) {
  return execSync(`git -C ${JSON.stringify(dir)} ${args}`, { stdio: ["ignore", "pipe", "ignore"] })
    .toString()
    .trim();
}

const FRESHNESS = {};
let counted = 0;
for (const file of walk(CONTENT)) {
  const fm = frontmatter(fs.readFileSync(file, "utf8"));
  const slug = (fm.codex_slug || "/" + path.relative(CONTENT, file).replace(/\.md$/, "")).trim();
  const sha = (fm.audited_against_sha || "").trim();
  if (!/^[0-9a-f]{6,40}$/i.test(sha)) continue; // skip "live", "unknown", empty
  const src = sourceRepo(fm.source);
  if (!src) continue;
  try {
    // Compare against the canonical branch when present, not a local feature checkout.
    let ref = "HEAD";
    try {
      git(src.dir, "rev-parse --verify --quiet origin/main");
      ref = "origin/main";
    } catch {
      /* no origin/main; use HEAD */
    }
    // Confirm the audited commit exists in that repo, then count how far the ref moved.
    git(src.dir, `cat-file -e ${sha}^{commit}`);
    const head = git(src.dir, `rev-parse --short ${ref}`);
    const behind = Number(git(src.dir, `rev-list --count ${sha}..${ref}`));
    const headDate = git(src.dir, `log -1 --format=%cs ${ref}`);
    FRESHNESS[slug] = { repo: src.repo, sha, head, behind: Number.isFinite(behind) ? behind : null, headDate };
    counted += 1;
  } catch {
    // audited sha not in the repo (rebased/squashed) -> record as unknown drift
    FRESHNESS[slug] = { repo: src.repo, sha, head: "", behind: null, headDate: "" };
  }
}

const banner =
  "// GENERATED by scripts/gen-freshness.mjs (npm run docs:freshness). Do not edit by hand.\n" +
  "// Per-page audit freshness: how far each source repo has moved since the page's audited_against_sha.\n";
const body =
  `${banner}export interface Freshness { repo: string; sha: string; head: string; behind: number | null; headDate: string }\n` +
  `export const FRESHNESS: Record<string, Freshness> = ${JSON.stringify(FRESHNESS, null, 2)};\n`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, body);
console.log(`[gen-freshness] wrote ${path.relative(ROOT, OUT)} (${counted} pages audited against a resolvable commit)`);
